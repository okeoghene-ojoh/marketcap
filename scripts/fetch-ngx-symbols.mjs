// Rewrites lib/ngx-symbols.ts with every NGX common stock listed by EODHD (uses 1 API call).
// Run from the marketcap folder:  node --env-file=.env.local scripts/fetch-ngx-symbols.mjs
import { writeFileSync } from "node:fs";

const key = process.env.EODHD_API_KEY;
if (!key) {
  console.error("EODHD_API_KEY isn't in .env.local yet. Run scripts\\set-keys.ps1 first.");
  process.exit(1);
}

const res = await fetch(`https://eodhd.com/api/exchange-symbol-list/XNSA?api_token=${encodeURIComponent(key)}&fmt=json`);
if (!res.ok) {
  console.error(`EODHD answered HTTP ${res.status}: ${(await res.text()).slice(0, 200)}`);
  process.exit(1);
}
const list = await res.json();
const stocks = list
  .filter((s) => s.Type === "Common Stock" && /^[A-Z0-9.\-]{1,12}$/.test(s.Code))
  .map((s) => ({ code: s.Code, name: String(s.Name).replace(/\s+/g, " ").trim() }))
  .sort((a, b) => a.code.localeCompare(b.code));

// A few NGX tickers are also US tickers (NEM = NEM Insurance here, Newmont in the US).
// The plain ticker stays American; the Nigerian one gets ".NG" (lib/providers/eodhd.ts strips it).
let clashes = new Set();
if (process.env.FINNHUB_API_KEY) {
  const us = await fetch(`https://finnhub.io/api/v1/stock/symbol?exchange=US&token=${encodeURIComponent(process.env.FINNHUB_API_KEY)}`);
  if (us.ok) clashes = new Set((await us.json()).map((x) => x.symbol));
  else console.warn(`Couldn't load the US ticker list (HTTP ${us.status}); clashes not checked.`);
} else {
  console.warn("No FINNHUB_API_KEY: clashes with US tickers not checked.");
}
const renamed = [];
for (const s of stocks) {
  if (clashes.has(s.code)) { renamed.push(s.code); s.code = `${s.code}.NG`; }
}
if (renamed.length) console.log(`Gave .NG to ${renamed.length} tickers that clash with US ones: ${renamed.join(", ")}`);

if (stocks.length < 20) {
  console.error(`Only ${stocks.length} NGX stocks came back; keeping the current file. (Does your plan include XNSA?)`);
  process.exit(1);
}

const titleCase = (s) => s.toLowerCase().replace(/\b(plc|ltd|nig|nigeria)\b/g, (w) => w).replace(/\b\w/g, (c) => c.toUpperCase());
const rows = stocks.map((s) => `  { code: ${JSON.stringify(s.code)}, name: ${JSON.stringify(titleCase(s.name))} },`).join("\n");
writeFileSync(
  new URL("../lib/ngx-symbols.ts", import.meta.url),
  `// NGX (Nigerian Exchange) listings Marketcap knows by name. Shared by the browser and the
// server: it decides which tickers are Nigerian (priced in naira, fetched from EODHD).
// Generated by scripts/fetch-ngx-symbols.mjs from EODHD's XNSA list on ${new Date().toISOString().slice(0, 10)}.
export const NGX_LIST: { code: string; name: string }[] = [
${rows}
];
`
);
console.log(`Wrote ${stocks.length} NGX stocks to lib/ngx-symbols.ts`);
